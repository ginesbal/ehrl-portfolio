async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('http://127.0.0.1:3101/#about')
  const avatar = page.getByRole('button', { name: 'Interact with the 3D avatar' })
  await avatar.waitFor({ state: 'visible' })
  await page.waitForFunction(() => document.querySelector('[aria-label="Interact with the 3D avatar"]')?.getAttribute('aria-busy') === 'false')
  await avatar.scrollIntoViewIfNeeded()
  await page.waitForTimeout(500)
  const canvas = avatar.locator('canvas')
  const sleep = avatar.locator('[data-avatar-sleep-effects]')
  const asleep = () => sleep.evaluate(element => !element.hidden)
  assert(await canvas.isVisible(), 'Avatar did not render')
  await avatar.screenshot({ path: 'output/playwright/avatar/working.png' })
  await page.clock.install({ time: new Date('2026-11-04T00:00:00Z') })
  await page.clock.pauseAt(new Date('2026-11-04T00:00:01Z'))
  await avatar.click({ force: true })
  await page.clock.runFor(650)
  assert((await avatar.locator('[aria-live]').textContent()).includes('Nice to see you'), 'Click did not wave')
  await avatar.screenshot({ path: 'output/playwright/avatar/wave.png' })
  await page.clock.runFor(1800)

  const box = await avatar.boundingBox()
  await page.mouse.move(box.x + box.width * .7, box.y + box.height * .6)
  await page.clock.fastForward(59000)
  assert(!await asleep(), 'Avatar slept before a minute')
  await page.mouse.move(box.x + box.width * .71, box.y + box.height * .6)
  await page.clock.fastForward(59999)
  assert(!await asleep(), 'Activity did not reset idle deadline')
  await page.clock.fastForward(2)
  await page.clock.runFor(1900)
  assert(await asleep(), 'Avatar did not fall asleep after a minute')
  assert(await sleep.locator('.avatar-zzz span').count() === 3, 'Sleeping zzz missing')
  assert(await sleep.locator('.avatar-nose-bubble').isVisible(), 'Sleeping nose bubble missing')
  await avatar.screenshot({ path: 'output/playwright/avatar/sleeping.png' })
  await page.mouse.move(0, 0)
  await page.mouse.move(box.x + box.width * .5, box.y + box.height * .5)
  await page.clock.runFor(300)
  assert(await asleep(), 'Hover incorrectly woke the avatar')
  await avatar.click({ force: true })
  await page.clock.runFor(1000)
  assert(!await asleep(), 'Click failed to wake the avatar')
  assert((await avatar.locator('[aria-live]').textContent()).includes('Back to work'), 'Wake feedback missing')
  const first = await canvas.screenshot()
  await page.clock.runFor(170)
  const second = await canvas.screenshot()
  assert(!first.equals(second), 'Typing did not resume after waking')
  await avatar.screenshot({ path: 'output/playwright/avatar/awake-again.png' })

  await avatar.click({ force: true })
  await page.clock.runFor(650)
  assert((await avatar.locator('[aria-live]').textContent()).includes('Nice to see you'), 'Second click failed to wave')
  await page.clock.fastForward(60001)
  await page.clock.runFor(1800)
  assert(await asleep(), 'Avatar did not sleep a second time')
  await avatar.focus()
  await page.keyboard.press('Enter')
  await page.clock.runFor(300)
  assert(!await asleep(), 'Keyboard failed to wake the avatar')

  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.fastForward(60001)
  await page.clock.runFor(100)
  assert(await asleep(), 'Reduced-motion sleep missing')
  const staticEffects = await sleep.evaluate(element => ({
    bubble: getComputedStyle(element.querySelector('.avatar-nose-bubble')).animationName,
    zzz: getComputedStyle(element.querySelector('.avatar-zzz span')).animationName,
  }))
  assert(staticEffects.bubble === 'none' && staticEffects.zzz === 'none', 'Reduced-motion effects still animate')
  await avatar.click({ force: true })
  await page.clock.runFor(100)
  assert(!await asleep(), 'Reduced-motion click failed to wake')
  assert(errors.length === 0, errors.join('; '))
  return { wave: 'passed', sleepAfter60Seconds: 'passed', idleReset: 'passed', zzzAndNoseBubble: 'visible', hoverDoesNotWake: 'passed', clickWakeAndResumeWork: 'passed', keyboardWake: 'passed', reducedMotion: staticEffects, browserErrors: errors }
}
