async page => {
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('http://127.0.0.1:3102/#about')
  const avatar = page.getByRole('button', { name: 'Interact with the 3D avatar' })
  await avatar.waitFor({ state: 'visible' })
  await page.waitForFunction(() => document.querySelector('[aria-label="Interact with the 3D avatar"]')?.getAttribute('aria-busy') === 'false')
  await avatar.scrollIntoViewIfNeeded()
  await page.waitForTimeout(500)
  const canvas = avatar.locator('canvas')
  const overlay = avatar.locator('[data-avatar-sleep-effects]')
  const liveText = () => avatar.locator('[aria-live]').textContent()
  const phase = () => overlay.evaluate(element => element.hidden ? 'hidden' : element.dataset.state)
  const capture = name => avatar.screenshot({ path: `output/playwright/avatar/${name}.png` })
  const mark = label => page.evaluate(name => console.info('AVATAR CHECK ' + name), label)
  const now = () => page.evaluate(() => performance.now())
  const advanceTo = async time => {
    const elapsed = Math.ceil(time - await now())
    if (elapsed > 0) await page.clock.fastForward(elapsed)
  }
  const box = await avatar.boundingBox()
  const point = { x: box.x + box.width / 2, y: box.y + box.height / 2 }
  const click = () => page.mouse.click(point.x, point.y)
  const activity = () => avatar.dispatchEvent('pointermove', {
    pointerType: 'mouse', clientX: point.x, clientY: point.y,
  })
  const startTime = new Date('2026-11-05T12:00:00Z')
  await page.clock.install({ time: startTime })
  await page.clock.pauseAt(new Date(startTime.getTime() + 1000))

  await click()
  await page.clock.runFor(650)
  const waveMessage = await liveText()
  assert(waveMessage, 'Wave feedback missing')
  const firstWave = await capture('wave-first-hand')
  await page.clock.fastForward(1450)
  await click()
  const lastInteraction = await now()
  await page.clock.runFor(650)
  const secondWave = await capture('wave-other-hand')
  assert(!firstWave.equals(secondWave), 'The two wave frames were identical')
  await mark('click-waves')

  await advanceTo(lastInteraction + 11010)
  await page.clock.runFor(650)
  await capture('wave-idle-hand')
  await advanceTo(lastInteraction + 19500)
  assert(await phase() === 'hidden', 'Avatar slept before 20 seconds')
  await advanceTo(lastInteraction + 20002)
  const napStarted = await now()
  await page.clock.runFor(950)
  assert(await phase() === 'sleeping', 'Avatar did not sleep after 20 seconds')
  assert(await overlay.locator('.avatar-nose-bubble').isVisible(), 'Sleeping bubble missing')
  assert(await overlay.locator('.avatar-zzz span').count() === 3, 'Sleeping zzz missing')
  await capture('nap-twenty-seconds')
  await mark('nap')

  await advanceTo(napStarted + 3410)
  assert(await phase() === 'popping', 'Automatic wake did not pop the bubble')
  await page.clock.runFor(170)
  await capture('wake-surprised')
  await page.clock.runFor(1450)
  assert(await phase() === 'hidden', 'Pop overlay stayed visible')
  const workingA = await canvas.screenshot()
  await page.clock.runFor(170)
  const workingB = await canvas.screenshot()
  assert(!workingA.equals(workingB), 'Typing did not resume after automatic wake')
  await mark('automatic-wake')

  await activity()
  await page.clock.fastForward(20002)
  await page.clock.runFor(650)
  assert(await phase() === 'sleeping', 'A second nap never started')
  await click()
  assert(await phase() === 'popping', 'Click did not pop the bubble')
  await page.clock.runFor(1450)
  assert(await phase() === 'hidden', 'Click wake did not finish')
  await mark('click-wake')

  await page.clock.fastForward(1300)
  await click()
  await page.clock.runFor(120)
  await click()
  await page.clock.runFor(120)
  await click()
  await page.clock.runFor(260)
  const annoyedMessage = await liveText()
  assert(annoyedMessage && annoyedMessage !== waveMessage, 'Three rapid clicks did not trigger distinct feedback')
  await capture('wave-annoyed')
  await mark('rapid-click-reaction')

  await page.emulateMedia({ reducedMotion: 'reduce' })
  await activity()
  await page.clock.fastForward(20002)
  assert(await phase() === 'sleeping', 'Reduced-motion nap missing')
  const bubbleMotion = await overlay.locator('.avatar-nose-bubble').evaluate(element => getComputedStyle(element).animationName)
  assert(bubbleMotion === 'none', 'Reduced-motion bubble animated')
  await click()
  assert(await phase() === 'hidden', 'Reduced-motion click wake did not hide the bubble immediately')
  assert(errors.length === 0, errors.join('; '))
  return { waveMessage, annoyedMessage, napsAfter20Seconds: true, automaticPop: true, clickPop: true,
    typingResumed: true, reducedMotionWake: true, browserErrors: errors }
}
